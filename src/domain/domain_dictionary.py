def domain_keywords_for_text(*values: str) -> list[str]:
    text = " ".join(value or "" for value in values).lower()
    tags: list[str] = []
    for tag, keywords in {**DOMAIN_KEYWORD_GROUPS, **TECHNICAL_DOMAIN_KEYWORD_GROUPS}.items():
        matched = [keyword for keyword in keywords if _keyword_in_text(keyword, text)]
        if not matched:
            continue
        _append_domain_keyword(tags, tag)
        for keyword in matched[:4]:
            _append_domain_keyword(tags, keyword)
    return tags[:24]


def _keyword_in_text(keyword: str, text: str) -> bool:
    value = (keyword or "").strip()
    if not value or value.lower() in {item.lower() for item in DOMAIN_KEYWORD_STOPWORDS}:
        return False
    return value.lower() in text


def _append_domain_keyword(values: list[str], keyword: str) -> None:
    cleaned = (keyword or "").strip()
    if not cleaned:
        return
    if cleaned.lower() in {item.lower() for item in DOMAIN_KEYWORD_STOPWORDS}:
        return
    if cleaned not in values:
        values.append(cleaned)
